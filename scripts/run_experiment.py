#!/usr/bin/env python3
"""
LunaFlow M4 -- traffic + measurement harness.

Usage:
  python3 run_experiment.py <scenario_dir> [--out DIR] [--lead S] [--keep] [--seed N]

<scenario_dir> is a tree generated by genscenario.py (e.g. ~/testbed/m4_smoke).
Its scenario.json must contain a "traffic" section:

  "traffic": {
    "end": 300,                  # stop measuring at T0+end   (default: duration)
    "sample_interval": 2,        # storage sampling period, s (default 2)
    "monitor": [20],             # nodes to sample           (default: all)
    "flows": [
      {"srcs": [101, 102], "dst": 30, "start": 15, "count": 20,
       "interval": 0.5, "size": 20000, "ttl": 3600, "class": "bulk",
       "jitter": 0.0}            # optional: uniform +-jitter s on each send time
    ]                            # "src": 101 is accepted for a single source
  }

One run =
  start_all.sh (boot + shared T0)  ->  bprecvfile at every flow destination
  -> one sender thread per (flow, src) calling bpsource on schedule
  -> sampler thread: `ionadmin m usage` per monitored node + ion.log event scan
  -> at T0+end: bpstats on every node, collect, stop_all.sh (unless --keep).

Every payload is tagged "LF1|<src>|<seq>|<class>|<t_sent_ms>|" and padded to
the flow's size, so delivery accounting needs nothing but the payloads.

Outputs in --out (default <repo>/results/<scenario>_<timestamp>/):
  bundles.csv     one row per generated bundle (sent/delivered times, status)
  buffer.csv      storage occupancy samples (MB) per monitored node
  events.csv      warnings/errors scraped from every node's ion.log
  node_stats.csv  final ION bpstats counters per node (src fwd xmt rcv dlv rfw exp)
  summary.json    headline metrics (delivery ratio overall + per class, latency,
                  peak occupancy vs cap, event counts)

WARNING: start_all.sh / stop_all.sh run `killm f` -- every ION node on the host dies.
"""
import argparse, csv, glob, json, os, random, re, signal, statistics
import subprocess, sys, threading, time
from datetime import datetime

MAGIC = "LF1"
MAX_PAYLOAD = 60000          # UDP CL limit is 65535 incl. BP headers; heapmax 65000

USAGE_RE = re.compile(
    r"current inbound heap ([\d.]+) MB, current inbound file space ([\d.]+) MB, "
    r"current outbound heap ([\d.]+) MB, current outbound file space ([\d.]+) MB")
STATS_RE = re.compile(
    r"\[x\] (\w+) from .*? to .*?: \(0\) (\d+) (\d+) \(1\) (\d+) (\d+) "
    r"\(2\) (\d+) (\d+) \(\+\) (\d+) (\d+)")
LOGTS_RE = re.compile(r"^\[(\d{4}/\d\d/\d\d-\d\d:\d\d:\d\d)\] (.*)$")
STATS_CATS = ["src", "fwd", "xmt", "rcv", "dlv", "rfw", "exp"]

# ion.log line -> event kind (first match wins)
EVENT_KINDS = [
    ("Can't acquire bundle",           "induct_failure"),  # udpcli dies: node goes deaf
    ("congested; discarding",          "congestion_discard"),
    ("ZCO space reservation",          "zco_wait"),
    ("[?]",                            "warning"),
    ("at line ",                       "error"),
]


def log(msg):
    print(f"[run_experiment] {msg}", flush=True)


class Run:
    def __init__(self, base, out, lead, seed):
        self.base, self.out, self.lead = base, out, lead
        self.scn = json.load(open(f"{base}/scenario.json"))
        self.tr = self.scn.get("traffic")
        if not self.tr or not self.tr.get("flows"):
            sys.exit("scenario.json has no traffic.flows -- nothing to run")
        self.rng = random.Random(seed)
        self.seed = seed
        self.nodes = {n["id"]: n for n in self.scn["nodes"]}
        self.end = self.tr.get("end", self.scn["duration"])
        self.sample_dt = self.tr.get("sample_interval", 2)
        self.monitor = self.tr.get("monitor", sorted(self.nodes))
        self.env = dict(os.environ, ION_NODE_LIST_DIR=base)
        self.lock = threading.Lock()
        self.bundles = {}                    # bundle_id -> row dict
        self.seq = {}                        # src -> next seq
        self.buffer_rows, self.event_rows = [], []
        self.log_offsets = {}
        self.stop = threading.Event()
        self.t0 = None
        self.flows = self._expand_flows()

    # ------------------------------------------------------------ setup
    def _expand_flows(self):
        flows = []
        for i, f in enumerate(self.tr["flows"]):
            srcs = f.get("srcs") or [f["src"]]
            for s in srcs:
                ff = dict(f, src=s, flow=i)
                ff.setdefault("dst", 30)
                ff.setdefault("interval", 1.0)
                ff.setdefault("ttl", 3600)
                ff.setdefault("class", "bulk")
                ff.setdefault("jitter", 0.0)
                for k in ("src", "dst"):
                    assert ff[k] in self.nodes, f"flow {i}: unknown node {ff[k]}"
                assert ff["size"] <= MAX_PAYLOAD, f"flow {i}: size > {MAX_PAYLOAD}"
                assert ff["size"] >= 64, f"flow {i}: size must be >= 64 (tag header)"
                flows.append(ff)
        return flows

    def ndir(self, n):
        return f"{self.base}/n{n}"

    def rel(self, t):
        return round(t - self.t0, 3)

    def wait_until(self, t):
        while not self.stop.is_set():
            dt = t - time.time()
            if dt <= 0:
                return True
            self.stop.wait(min(dt, 0.5))
        return False

    # ------------------------------------------------------------ senders
    def sender(self, f):
        for k in range(f["count"]):
            sched = self.t0 + f["start"] + k * f["interval"]
            if f["jitter"]:
                sched += self.rng.uniform(-f["jitter"], f["jitter"])
            if not self.wait_until(sched):
                return
            with self.lock:
                seq = self.seq.get(f["src"], 0)
                self.seq[f["src"]] = seq + 1
            bid = f"{f['src']}:{seq}"
            t_sent = time.time()
            hdr = f"{MAGIC}|{f['src']}|{seq}|{f['class']}|{int(t_sent * 1000)}|"
            payload = hdr + "." * (f["size"] - len(hdr))
            row = dict(bundle_id=bid, src=f["src"], dst=f["dst"], seq=seq,
                       flow=f["flow"], cls=f["class"], size=f["size"], ttl=f["ttl"],
                       t_sched=self.rel(sched), t_sent=self.rel(t_sent),
                       send_s="", t_delivered="", latency="", status="NOT_SENT")
            with self.lock:
                self.bundles[bid] = row
            # bpsource blocks (no loss) while its node's outbound storage is full;
            # the call duration is recorded as send_s = source-side backpressure.
            p = subprocess.Popen(["bpsource", f"ipn:{f['dst']}.1", payload,
                                  f"-t{f['ttl']}"], cwd=self.ndir(f["src"]),
                                 env=self.env, stdout=subprocess.DEVNULL,
                                 stderr=subprocess.PIPE, text=True)
            while p.poll() is None and not self.stop.is_set():
                time.sleep(0.02)
            if p.poll() is None:            # run ended while still blocked
                p.kill()
                p.wait()
                row["status"] = "SEND_BLOCKED"
                return
            err = p.stderr.read()
            with self.lock:
                row["send_s"] = round(time.time() - t_sent, 3)
                if p.returncode != 0 or "failed" in err:
                    row["status"] = "SEND_FAILED"
                elif row["status"] == "NOT_SENT":
                    row["status"] = "UNDELIVERED"

    # ------------------------------------------------------------ receivers
    def collect_deliveries(self, dst, final=False):
        for path in sorted(glob.glob(f"{self.ndir(dst)}/testfile*")):
            try:
                st = os.stat(path)
                with open(path, "r", errors="replace") as fh:
                    head = fh.read(128)
            except FileNotFoundError:
                continue
            parts = head.split("|")
            if len(parts) < 6 or parts[0] != MAGIC:
                if final or time.time() - st.st_mtime > 5:
                    self.event(dst, st.st_mtime, "foreign_payload", head[:60])
                    os.remove(path)
                continue
            bid = f"{parts[1]}:{parts[2]}"
            with self.lock:
                row = self.bundles.get(bid)
            if row and st.st_size < row["size"] and not final:
                continue                     # bprecvfile still writing it
            with self.lock:
                if row is None:
                    self.event(dst, st.st_mtime, "unknown_bundle", bid)
                elif row["t_delivered"] == "":
                    t_dlv = self.rel(st.st_mtime)
                    row["t_delivered"] = t_dlv
                    row["latency"] = round(t_dlv - row["t_sent"], 3)
                    row["status"] = ("DELIVERED" if row["latency"] <= row["ttl"]
                                     else "DELIVERED_LATE")
                else:
                    self.event(dst, st.st_mtime, "duplicate_delivery", bid)
            os.remove(path)

    # ------------------------------------------------------------ sampling
    def ionadmin_usage(self, n):
        try:
            r = subprocess.run(["ionadmin", "../usage.ionrc"], cwd=self.ndir(n),
                               env=self.env, capture_output=True, text=True,
                               timeout=15)
        except subprocess.TimeoutExpired:
            return None
        m = USAGE_RE.search(r.stdout)
        return [float(x) for x in m.groups()] if m else None

    def event(self, node, epoch, kind, msg):
        self.event_rows.append(dict(t=self.rel(epoch), node=node, kind=kind,
                                    msg=msg.strip()[:200]))

    def scan_logs(self):
        for n in self.nodes:
            path = f"{self.ndir(n)}/ion.log"
            try:
                with open(path, errors="replace") as fh:
                    fh.seek(self.log_offsets.get(n, 0))
                    data = fh.read()
                    self.log_offsets[n] = fh.tell()
            except FileNotFoundError:
                continue
            for line in data.splitlines():
                m = LOGTS_RE.match(line)
                if not m:
                    continue
                msg = m.group(2)
                for pat, kind in EVENT_KINDS:
                    if pat in msg:
                        epoch = time.mktime(time.strptime(m.group(1), "%Y/%m/%d-%H:%M:%S"))
                        with self.lock:
                            self.event(n, epoch, kind, msg)
                        break

    def cap_mb(self, n):
        return self.nodes[n].get("buffer_mb", "")

    def sampler(self):
        nxt = self.t0
        while self.wait_until(nxt):
            t = time.time()
            for n in self.monitor:
                u = self.ionadmin_usage(n)
                if u is None:
                    with self.lock:
                        self.event(n, t, "sample_failed", "ionadmin m usage gave no result")
                    continue
                self.buffer_rows.append(dict(
                    t=self.rel(t), node=n, in_heap_mb=u[0], in_file_mb=u[1],
                    out_heap_mb=u[2], out_file_mb=u[3],
                    total_mb=round(sum(u), 2), cap_mb=self.cap_mb(n)))
            for dst in {f["dst"] for f in self.flows}:
                self.collect_deliveries(dst)
            self.scan_logs()
            nxt += self.sample_dt
            if nxt > self.t0 + self.end:
                return

    # ------------------------------------------------------------ final stats
    def collect_bpstats(self):
        for n in self.nodes:
            subprocess.run(["bpstats"], cwd=self.ndir(n), env=self.env,
                           capture_output=True, timeout=15)
        time.sleep(1.5)
        rows = []
        for n in self.nodes:
            last = {}
            try:
                for line in open(f"{self.ndir(n)}/ion.log", errors="replace"):
                    m = STATS_RE.search(line)
                    if m:
                        last[m.group(1)] = [int(x) for x in m.groups()[1:]]
            except FileNotFoundError:
                pass
            for cat in STATS_CATS:
                v = last.get(cat, [""] * 8)
                rows.append(dict(node=n, type=self.nodes[n].get("type", ""), stat=cat,
                                 p0_n=v[0], p0_b=v[1], p1_n=v[2], p1_b=v[3],
                                 p2_n=v[4], p2_b=v[5], total_n=v[6], total_b=v[7]))
        return rows

    # ------------------------------------------------------------ main
    def run(self, keep):
        os.makedirs(self.out, exist_ok=True)
        open(f"{self.base}/usage.ionrc", "w").write("m usage\n")
        for dst in {f["dst"] for f in self.flows}:
            for p in glob.glob(f"{self.ndir(dst)}/testfile*"):
                os.remove(p)

        log(f"booting {len(self.nodes)} nodes (lead {self.lead}s)")
        r = subprocess.run([f"{self.base}/start_all.sh", str(self.lead)],
                           capture_output=True, text=True)
        open(f"{self.out}/start_all.log", "w").write(r.stdout + r.stderr)
        if r.returncode != 0:
            sys.exit(f"start_all.sh failed (rc={r.returncode}); see {self.out}/start_all.log")
        self.t0 = int(open(f"{self.base}/t0.txt").read())
        log(f"T0 = {self.t0} ({datetime.fromtimestamp(self.t0)}); measuring until T0+{self.end}s")

        receivers = []
        for dst in sorted({f["dst"] for f in self.flows}):
            receivers.append(subprocess.Popen(
                ["bprecvfile", f"ipn:{dst}.1"], cwd=self.ndir(dst), env=self.env,
                stdout=open(f"{self.ndir(dst)}/bprecvfile.log", "w"),
                stderr=subprocess.STDOUT))

        threads = [threading.Thread(target=self.sampler, daemon=True)]
        threads += [threading.Thread(target=self.sender, args=(f,), daemon=True)
                    for f in self.flows]
        for t in threads:
            t.start()
        total = sum(f["count"] for f in self.flows)
        log(f"{len(self.flows)} sender(s), {total} bundles scheduled")

        def interrupt(*_):
            log("interrupted -- finishing early")
            self.stop.set()
        signal.signal(signal.SIGINT, interrupt)

        while time.time() < self.t0 + self.end and not self.stop.is_set():
            self.stop.wait(10)
            with self.lock:
                dl = sum(1 for b in self.bundles.values() if b["t_delivered"] != "")
                sent = len(self.bundles)
            log(f"T0+{int(time.time() - self.t0)}s  sent {sent}/{total}  delivered {dl}")
        self.stop.set()
        for t in threads:
            t.join(timeout=20)

        for p in receivers:                 # SIGINT -> bprecvfile detaches cleanly
            p.send_signal(signal.SIGINT)
        for p in receivers:
            try:
                p.wait(timeout=10)
            except subprocess.TimeoutExpired:
                p.kill()
        for dst in {f["dst"] for f in self.flows}:
            self.collect_deliveries(dst, final=True)
        self.scan_logs()
        stats = self.collect_bpstats()
        self.scan_logs()

        if not keep:
            subprocess.run([f"{self.base}/stop_all.sh"], capture_output=True)
        self.write(stats)

    def write(self, stats):
        def dump(name, rows, fields):
            with open(f"{self.out}/{name}", "w", newline="") as fh:
                w = csv.DictWriter(fh, fieldnames=fields)
                w.writeheader()
                w.writerows(rows)
        bundles = sorted(self.bundles.values(), key=lambda b: (b["t_sent"], b["bundle_id"]))
        dump("bundles.csv", bundles, list(bundles[0]) if bundles else ["bundle_id"])
        dump("buffer.csv", self.buffer_rows,
             ["t", "node", "in_heap_mb", "in_file_mb", "out_heap_mb", "out_file_mb",
              "total_mb", "cap_mb"])
        events = sorted(self.event_rows, key=lambda e: e["t"])
        dump("events.csv", events, ["t", "node", "kind", "msg"])
        dump("node_stats.csv", stats, list(stats[0]))
        summary = self.summarize(bundles, events)
        json.dump(summary, open(f"{self.out}/summary.json", "w"), indent=2)
        shown = {k: v for k, v in summary.items() if k != "scenario_file"}
        print(json.dumps(shown, indent=2))
        log(f"results: {self.out}")

    def summarize(self, bundles, events):
        def ratio(bs):
            n = len(bs)
            d = sum(1 for b in bs if b["status"] == "DELIVERED")
            return dict(generated=n, delivered=d,
                        delivery_ratio=round(d / n, 4) if n else None)
        lat = [b["latency"] for b in bundles if b["status"] == "DELIVERED"]
        status = {}
        for b in bundles:
            status[b["status"]] = status.get(b["status"], 0) + 1
        peaks = {}
        for r in self.buffer_rows:
            p = peaks.setdefault(r["node"], dict(peak_mb=0.0, t_peak=None,
                                                 cap_mb=r["cap_mb"]))
            if r["total_mb"] > p["peak_mb"]:
                p["peak_mb"], p["t_peak"] = r["total_mb"], r["t"]
        kinds = {}
        for e in events:
            if e["t"] >= 0:                  # ignore boot-time noise
                kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
        induct_down = sorted({(e["node"], e["t"]) for e in events
                              if e["kind"] == "induct_failure"})
        return dict(
            scenario=self.scn["name"], t0=self.t0, end=self.end, seed=self.seed,
            **ratio(bundles),
            by_class={c: ratio([b for b in bundles if b["cls"] == c])
                      for c in sorted({b["cls"] for b in bundles})},
            by_src={str(s): ratio([b for b in bundles if b["src"] == s])
                    for s in sorted({b["src"] for b in bundles})},
            status_counts=status,
            latency_s=dict(mean=round(statistics.mean(lat), 2),
                           p50=round(statistics.median(lat), 2),
                           p95=round(sorted(lat)[int(0.95 * (len(lat) - 1))], 2),
                           max=round(max(lat), 2)) if lat else None,
            storage_peak=peaks,
            event_counts=kinds,
            induct_failures=[dict(node=n, t=t) for n, t in induct_down],
            scenario_file=f"{self.base}/scenario.json")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("scenario_dir")
    ap.add_argument("--out", help="results dir (default <repo>/results/<name>_<ts>)")
    ap.add_argument("--lead", type=int, default=15, help="seconds from contact load to T0")
    ap.add_argument("--keep", action="store_true", help="leave nodes running afterwards")
    ap.add_argument("--seed", type=int, default=0, help="RNG seed for send jitter")
    a = ap.parse_args()
    base = os.path.abspath(os.path.expanduser(a.scenario_dir))
    scn = json.load(open(f"{base}/scenario.json"))
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = a.out or f"{repo}/results/{scn['name']}_{datetime.now():%Y%m%d-%H%M%S}"
    Run(base, os.path.abspath(out), a.lead, a.seed).run(a.keep)


if __name__ == "__main__":
    main()
